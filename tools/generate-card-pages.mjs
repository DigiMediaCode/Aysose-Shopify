/*
 * Builds the data for the one-page-per-graphics-card pages from the same parts lists and
 * estimates the checker uses (assets/pc-checker.js). Run it whenever the estimates or the card
 * list change, then commit the snippet it rewrites:
 *
 *   node tools/generate-card-pages.mjs
 *
 * It writes snippets/pc-card-data.liquid, which holds one line per card:
 *   video memory | one letter per quality level (p = should run, n = borderline, f = unlikely)
 *   | one letter per level saying why (- nothing, s = speed, v = video memory, b = both)
 *   | highest level that passes (-1 if none) | first level that does not pass (-1 if none)
 *   | highest level that passes as a laptop card | next card down | next card up
 * and prints the page titles as JSON. A card page only needs the title "Can the <card> run GTA 6?"
 * and the page template "gpu-check"; sections/pc-checker.liquid writes the text from the snippet.
 * The level names and example parts are repeated in that section, so keep them in step with TIERS.
 */
import fs from 'node:fs';
import { GPUS, TIERS, checkTier } from '../assets/pc-checker.js';

const LAPTOP_FACTOR = 0.8;
const LETTER = { pass: 'p', near: 'n', fail: 'f' };

const cards = Object.values(GPUS)
  .flat()
  .filter((card) => card[0] !== 'Built-in graphics only')
  .map(([name, score, vram]) => ({ name, score, vram }));

// Judge the card on its own: assume the processor, memory and drive are not the limit.
const judge = (score, vram) =>
  TIERS.map((tier) => checkTier({ gpu: score, vram, cpu: 999, ram: 64, ssd: true }, tier));
const bestIndex = (results) => results.map((result) => result.status).lastIndexOf('pass');

const sorted = [...cards].sort((a, b) => a.score - b.score);

const rows = cards.map((card) => {
  const results = judge(card.score, card.vram);
  const index = sorted.findIndex((other) => other.name === card.name);
  const slower = [...sorted.slice(0, index)].reverse().find((other) => other.score < card.score);
  const faster = sorted.slice(index + 1).find((other) => other.score > card.score);
  const fields = [
    card.vram,
    results.map((result) => LETTER[result.status]).join(''),
    results
      .map(({ parts }) => {
        const speed = parts.gpu !== 'pass';
        const memory = parts.vram !== 'pass';
        return speed && memory ? 'b' : speed ? 's' : memory ? 'v' : '-';
      })
      .join(''),
    bestIndex(results),
    results.findIndex((result) => result.status !== 'pass'),
    bestIndex(judge(Math.round(card.score * LAPTOP_FACTOR), card.vram)),
    slower ? slower.name : '',
    faster ? faster.name : '',
  ];
  return { name: card.name, row: fields.join('|') };
});

const snippet = [
  '{%- doc -%}',
  '  Generated by tools/generate-card-pages.mjs. Do not edit by hand.',
  '  Outputs the estimate data for one graphics card, or nothing if the card is not in the list.',
  '',
  '  @param {string} name - The card name, exactly as the checker lists it.',
  '{%- enddoc -%}',
  '{%- case name -%}',
  ...rows.map(({ name, row }) => `  {%- when '${name}' -%}\n    ${row}`),
  '{%- endcase -%}',
  '',
].join('\n');
fs.writeFileSync(new URL('../snippets/pc-card-data.liquid', import.meta.url), snippet);

process.stdout.write(JSON.stringify(rows.map(({ name }) => `Can the ${name} run GTA 6?`), null, 2));
