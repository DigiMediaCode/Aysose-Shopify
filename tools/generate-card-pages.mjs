/*
 * Builds the data for the one-page-per-graphics-card pages from the same parts lists and
 * estimates the checker uses (assets/pc-checker.js). Run it whenever the estimates or the card
 * list change, then commit the snippet it rewrites:
 *
 *   node tools/generate-card-pages.mjs
 *
 * It writes snippets/pc-card-data.liquid, which holds one line per card:
 *   video memory | one letter per quality level (p = should run, n = borderline, f = unlikely)
 *   | one letter per level saying why (- nothing, s = speed, v = video memory, b = both)
 *   | highest level that passes (-1 if none) | first level that does not pass (-1 if none)
 *   | highest level that passes as a laptop card | next card down | next card up
 * It also writes snippets/pc-card-links.liquid (the list of links to every card page)
 * and prints the page titles as JSON. A card page only needs the title "Can the <card> run GTA 6?"
 * and the page template "gpu-check"; sections/pc-checker.liquid writes the text from the snippet.
 * The level names and example parts are repeated in that section, so keep them in step with TIERS.
 *
 * Processor pages work the same way (same title pattern, same page template). The script writes
 * snippets/pc-cpu-data.liquid, one line per processor:
 *   one letter per quality level (p / n / f) | highest level that passes (-1 if none)
 *   | first level that does not pass (-1 if none) | next processor down | next processor up
 * and snippets/pc-cpu-links.liquid. The titles it prints list the graphics cards first, then the processors.
 *
 * Upgrade guide pages ("Best graphics card for GTA 6 at 1440p", see GUIDES below) use the same page
 * template. The script writes snippets/pc-best-data.liquid (the suggested parts per quality level)
 * and snippets/pc-best-links.liquid. No prices are stored or shown anywhere.
 */
import fs from 'node:fs';
import { GPUS, CPUS, TIERS, checkTier } from '../assets/pc-checker.js';

const LAPTOP_FACTOR = 0.8;
const LETTER = { pass: 'p', near: 'n', fail: 'f' };

const cards = Object.values(GPUS)
  .flat()
  .filter((card) => card[0] !== 'Built-in graphics only')
  .map(([name, score, vram]) => ({ name, score, vram }));

// Judge the card on its own: assume the processor, memory and drive are not the limit.
const judge = (score, vram) =>
  TIERS.map((tier) => checkTier({ gpu: score, vram, cpu: 999, ram: 64, ssd: true }, tier));
const bestIndex = (results) => results.map((result) => result.status).lastIndexOf('pass');

const sorted = [...cards].sort((a, b) => a.score - b.score);

const rows = cards.map((card) => {
  const results = judge(card.score, card.vram);
  const index = sorted.findIndex((other) => other.name === card.name);
  const slower = [...sorted.slice(0, index)].reverse().find((other) => other.score < card.score);
  const faster = sorted.slice(index + 1).find((other) => other.score > card.score);
  const fields = [
    card.vram,
    results.map((result) => LETTER[result.status]).join(''),
    results
      .map(({ parts }) => {
        const speed = parts.gpu !== 'pass';
        const memory = parts.vram !== 'pass';
        return speed && memory ? 'b' : speed ? 's' : memory ? 'v' : '-';
      })
      .join(''),
    bestIndex(results),
    results.findIndex((result) => result.status !== 'pass'),
    bestIndex(judge(Math.round(card.score * LAPTOP_FACTOR), card.vram)),
    slower ? slower.name : '',
    faster ? faster.name : '',
  ];
  return { name: card.name, row: fields.join('|') };
});

const snippet = [
  '{%- doc -%}',
  '  Generated by tools/generate-card-pages.mjs. Do not edit by hand.',
  '  Outputs the estimate data for one graphics card, or nothing if the card is not in the list.',
  '',
  '  @param {string} name - The card name, exactly as the checker lists it.',
  '{%- enddoc -%}',
  '{%- case name -%}',
  ...rows.map(({ name, row }) => `  {%- when '${name}' -%}\n    ${row}`),
  '{%- endcase -%}',
  '',
].join('\n');
fs.writeFileSync(new URL('../snippets/pc-card-data.liquid', import.meta.url), snippet);

const handleize = (text) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const links = [
  '{%- doc -%}',
  '  Generated by tools/generate-card-pages.mjs. Do not edit by hand.',
  '  Outputs one list item linking to each graphics card page.',
  '{%- enddoc -%}',
  ...rows.map(
    ({ name }) =>
      `<li><a href="{{ routes.root_url }}pages/${handleize(`Can the ${name} run GTA 6?`)}">${name}</a></li>`
  ),
  '',
].join('\n');
fs.writeFileSync(new URL('../snippets/pc-card-links.liquid', import.meta.url), links);

// Processors: judge each one on its own, assuming the graphics card, memory and drive are not the limit.
const processors = Object.values(CPUS)
  .flat()
  .map(([name, score]) => ({ name, score }));
const sortedProcessors = [...processors].sort((a, b) => a.score - b.score);
const processorRows = processors.map((processor) => {
  const results = TIERS.map((tier) =>
    checkTier({ gpu: 9999, vram: 64, cpu: processor.score, ram: 64, ssd: true }, tier)
  );
  const index = sortedProcessors.findIndex((other) => other.name === processor.name);
  const slower = [...sortedProcessors.slice(0, index)].reverse().find((other) => other.score < processor.score);
  const faster = sortedProcessors.slice(index + 1).find((other) => other.score > processor.score);
  const fields = [
    results.map((result) => LETTER[result.status]).join(''),
    bestIndex(results),
    results.findIndex((result) => result.status !== 'pass'),
    slower ? slower.name : '',
    faster ? faster.name : '',
  ];
  return { name: processor.name, row: fields.join('|') };
});

fs.writeFileSync(
  new URL('../snippets/pc-cpu-data.liquid', import.meta.url),
  [
    '{%- doc -%}',
    '  Generated by tools/generate-card-pages.mjs. Do not edit by hand.',
    '  Outputs the estimate data for one processor, or nothing if the processor is not in the list.',
    '',
    '  @param {string} name - The processor name, exactly as the checker lists it.',
    '{%- enddoc -%}',
    '{%- case name -%}',
    ...processorRows.map(({ name, row }) => `  {%- when '${name}' -%}\n    ${row}`),
    '{%- endcase -%}',
    '',
  ].join('\n')
);
fs.writeFileSync(
  new URL('../snippets/pc-cpu-links.liquid', import.meta.url),
  [
    '{%- doc -%}',
    '  Generated by tools/generate-card-pages.mjs. Do not edit by hand.',
    '  Outputs one list item linking to each processor page.',
    '{%- enddoc -%}',
    ...processorRows.map(
      ({ name }) =>
        `<li><a href="{{ routes.root_url }}pages/${handleize(`Can the ${name} run GTA 6?`)}">${name}</a></li>`
    ),
    '',
  ].join('\n')
);

// Upgrade guides: for each quality level, the three least powerful parts still sold new that clear
// the level on their own (usually the cheapest way to reach it). Only current ranges are considered.
const CURRENT_GPU_GROUPS = ['Nvidia GeForce RTX 50', 'AMD Radeon RX 9000', 'Intel Arc'];
const CURRENT_GPU_SKIP = ['Arc A770 16GB', 'Arc A750'];
const CURRENT_CPU_GROUPS = [
  'AMD Ryzen 9000',
  'AMD Ryzen 7000',
  'AMD Ryzen 5000',
  'Intel Core Ultra',
  'Intel Core 13th and 14th gen',
];
const currentCards = CURRENT_GPU_GROUPS.flatMap((group) => GPUS[group])
  .filter(([name]) => !CURRENT_GPU_SKIP.includes(name))
  .map(([name, score, vram]) => ({ name, score, vram }))
  .sort((a, b) => a.score - b.score);
const currentProcessors = CURRENT_CPU_GROUPS.flatMap((group) => CPUS[group])
  .map(([name, score]) => ({ name, score }))
  .sort((a, b) => a.score - b.score);
const PICKS = 3;
const bestRows = TIERS.flatMap((tier, index) => [
  {
    key: `gpu${index}`,
    row: currentCards
      .filter((card) => card.score >= tier.gpu && card.vram >= tier.vram)
      .slice(0, PICKS)
      .map((card) => `${card.name}~${card.vram}`)
      .join(';'),
  },
  {
    key: `cpu${index}`,
    row: currentProcessors
      .filter((processor) => processor.score >= tier.cpu)
      .slice(0, PICKS)
      .map((processor) => processor.name)
      .join(';'),
  },
]);
fs.writeFileSync(
  new URL('../snippets/pc-best-data.liquid', import.meta.url),
  [
    '{%- doc -%}',
    '  Generated by tools/generate-card-pages.mjs. Do not edit by hand.',
    '  Outputs the suggested parts for one quality level: names separated by ";". Graphics cards carry',
    '  their video memory after "~".',
    '',
    '  @param {string} key - "gpu" or "cpu" followed by the level number, for example "gpu2".',
    '{%- enddoc -%}',
    '{%- case key -%}',
    ...bestRows.map(({ key, row }) => `  {%- when '${key}' -%}\n    ${row}`),
    '{%- endcase -%}',
    '',
  ].join('\n')
);
const GUIDES = [
  'Best graphics card for GTA 6 on PC',
  'Best graphics card for GTA 6 at 1080p',
  'Best graphics card for GTA 6 at 1440p',
  'Best graphics card for GTA 6 at 4K',
  'Best processor for GTA 6 on PC',
];
fs.writeFileSync(
  new URL('../snippets/pc-best-links.liquid', import.meta.url),
  [
    '{%- doc -%}',
    '  Generated by tools/generate-card-pages.mjs. Do not edit by hand.',
    '  Outputs one list item linking to each upgrade guide page.',
    '{%- enddoc -%}',
    ...GUIDES.map((title) => `<li><a href="{{ routes.root_url }}pages/${handleize(title)}">${title}</a></li>`),
    '',
  ].join('\n')
);

process.stdout.write(
  JSON.stringify(
    [...rows, ...processorRows].map(({ name }) => `Can the ${name} run GTA 6?`),
    null,
    2
  )
);
